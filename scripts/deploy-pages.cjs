// Builds the app and publishes dist/ to the gh-pages branch (what GitHub Pages serves). Run after `npm test`.
const { execFileSync } = require('child_process')
const fs = require('fs')
const os = require('os')
const path = require('path')
const root = path.join(__dirname, '..')
const run = (cwd, ...a) => execFileSync('git', a, { cwd, stdio: ['ignore', 'pipe', 'inherit'] }).toString().trim()
execFileSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['run', 'build'], { cwd: root, stdio: 'inherit', shell: process.platform === 'win32' })
const remote = run(root, 'remote', 'get-url', 'origin')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'wg-pages-'))
fs.cpSync(path.join(root, 'dist'), tmp, { recursive: true })
fs.writeFileSync(path.join(tmp, '.nojekyll'), '')
run(tmp, 'init', '-q', '-b', 'gh-pages')
run(tmp, 'add', '-A')
const msg = 'Publish app ' + new Date().toISOString() + '\n\nCo-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>'
run(tmp, '-c', 'user.name=Woodland Gantt', '-c', 'user.email=woodlandarchitects.in@gmail.com', 'commit', '-q', '-m', msg)
run(tmp, 'push', '-q', '--force', remote, 'gh-pages')
fs.rmSync(tmp, { recursive: true, force: true })
console.log('published to gh-pages')
